import Foundation

/// Output of an individual subscanner pass.
public struct SubscannerResult: Sendable {
    public let candidates: [ScanCandidateItem]
    public let skippedProtectedCount: Int

    public init(candidates: [ScanCandidateItem], skippedProtectedCount: Int) {
        self.candidates = candidates
        self.skippedProtectedCount = skippedProtectedCount
    }
}

/// Protocol implemented by all modular cleanup subscanners.
public protocol CleanupSubscanner: Sendable {
    var identifier: String { get }
    var progressWeight: Double { get }
    func scan(
        safetyEngine: SafetyGuardEngine,
        appCatalog: ApplicationMetadataCatalog
    ) -> SubscannerResult
}

extension CleanupSubscanner {
    public var progressWeight: Double {
        ScanProgressTracker.weight(for: identifier) ?? 0.14
    }
}

// MARK: - 1. Application Caches Subscanner (~/Library/Caches + Sandbox Containers)

public struct ApplicationCacheSubscanner: CleanupSubscanner {
    public let identifier = "scanner.app_caches"
    public init() {}

    public func scan(
        safetyEngine: SafetyGuardEngine,
        appCatalog: ApplicationMetadataCatalog
    ) -> SubscannerResult {
        var candidates: [ScanCandidateItem] = []
        var skipped = 0
        let fm = FileManager.default
        let home = safetyEngine.homeDirectoryPath
        let rules = safetyEngine.rules

        // 1A. ~/Library/Caches/*
        let userCachesRoot = (home as NSString).appendingPathComponent("Library/Caches")
        if let entries = try? fm.contentsOfDirectory(atPath: userCachesRoot) {
            for entry in entries where !entry.hasPrefix(".") {
                if rules.browserCacheFolderIdentifiers.contains(entry)
                    || rules.developerLibraryCacheFolderIdentifiers.contains(entry)
                {
                    continue
                }
                let fullPath = (userCachesRoot as NSString).appendingPathComponent(entry)
                let resolved = appCatalog.resolve(folderOrBundleIdentifier: entry)
                let verdict = safetyEngine.evaluate(
                    path: fullPath,
                    category: .applicationCaches,
                    bundleIdentifier: resolved.bundleID,
                    displayName: resolved.displayName,
                    defaultConfidence: .safeAutoSelect,
                    defaultReason:
                        "Standard macOS user application cache in ~/Library/Caches; automatically regenerated by \(resolved.displayName)."
                )
                guard verdict.isAllowed else {
                    skipped += 1
                    continue
                }
                let metrics = DiskAllocatedSizeCalculator.measure(
                    path: fullPath,
                    protectedComponentNames: rules.protectedCacheComponents
                )
                guard metrics.allocatedBytes > 0 else { continue }
                candidates.append(
                    ScanCandidateItem(
                        path: fullPath,
                        category: .applicationCaches,
                        bundleIdentifier: resolved.bundleID,
                        appDisplayName: resolved.displayName,
                        itemName: "\(resolved.displayName) Cache (\(entry))",
                        allocatedBytes: metrics.allocatedBytes,
                        fileCount: metrics.fileCount,
                        lastModified: metrics.latestModified,
                        confidence: verdict.confidence,
                        isRunningApp: verdict.isRunningApp,
                        ruleIdentifier: "cache.user.\(entry)",
                        safetyExplanation: verdict.reason
                    )
                )
            }
        }

        // 1B. ~/Library/Containers/*/Data/Library/Caches/*
        let containersRoot = (home as NSString).appendingPathComponent("Library/Containers")
        if let containers = try? fm.contentsOfDirectory(atPath: containersRoot) {
            for containerID in containers where !containerID.hasPrefix(".") {
                if containerID.hasPrefix("com.apple.") { continue }
                let cacheDir = (containersRoot as NSString).appendingPathComponent("\(containerID)/Data/Library/Caches")
                var isDir: ObjCBool = false
                guard fm.fileExists(atPath: cacheDir, isDirectory: &isDir), isDir.boolValue else { continue }
                guard let cacheEntries = try? fm.contentsOfDirectory(atPath: cacheDir), !cacheEntries.isEmpty else {
                    continue
                }

                let resolved = appCatalog.resolve(folderOrBundleIdentifier: containerID)
                for entry in cacheEntries where !entry.hasPrefix(".") {
                    let entryPath = (cacheDir as NSString).appendingPathComponent(entry)
                    let verdict = safetyEngine.evaluate(
                        path: entryPath,
                        category: .applicationCaches,
                        bundleIdentifier: resolved.bundleID,
                        displayName: resolved.displayName,
                        defaultConfidence: .safeAutoSelect,
                        defaultReason:
                            "App Sandbox container cache entry (\(entry)); isolated from user documents and preferences."
                    )
                    guard verdict.isAllowed else {
                        skipped += 1
                        continue
                    }
                    let metrics = DiskAllocatedSizeCalculator.measure(
                        path: entryPath,
                        protectedComponentNames: rules.protectedCacheComponents
                    )
                    guard metrics.allocatedBytes > 0 else { continue }
                    candidates.append(
                        ScanCandidateItem(
                            path: entryPath,
                            category: .applicationCaches,
                            bundleIdentifier: resolved.bundleID,
                            appDisplayName: resolved.displayName,
                            itemName: "\(resolved.displayName) Sandbox Cache (\(entry))",
                            allocatedBytes: metrics.allocatedBytes,
                            fileCount: metrics.fileCount,
                            lastModified: metrics.latestModified,
                            confidence: verdict.confidence,
                            isRunningApp: verdict.isRunningApp,
                            ruleIdentifier: "cache.sandbox.\(containerID).\(entry)",
                            safetyExplanation: verdict.reason
                        )
                    )
                }
            }
        }

        return SubscannerResult(candidates: candidates, skippedProtectedCount: skipped)
    }
}

// MARK: - 2. Electron & Web App Support Caches Subscanner

public struct ElectronAndWebAppCacheSubscanner: CleanupSubscanner {
    public let identifier = "scanner.electron_caches"
    public init() {}

    private let browserRootNames: Set<String> = [
        "Google", "BraveSoftware", "Microsoft Edge", "Firefox", "Mozilla", "com.operasoftware.Opera", "Vivaldi",
        "Yandex",
    ]

    private let aiDesktopAppFolderNames: Set<String> = [
        "Claude", "Antigravity", "Cursor", "Windsurf", "ChatGPT", "LM Studio", "Ollama",
    ]

    public func scan(
        safetyEngine: SafetyGuardEngine,
        appCatalog: ApplicationMetadataCatalog
    ) -> SubscannerResult {
        var candidates: [ScanCandidateItem] = []
        var skipped = 0
        let fm = FileManager.default
        let appSupportRoot = (safetyEngine.homeDirectoryPath as NSString).appendingPathComponent(
            "Library/Application Support")
        let rules = safetyEngine.rules

        guard let appFolders = try? fm.contentsOfDirectory(atPath: appSupportRoot) else {
            return SubscannerResult(candidates: [], skippedProtectedCount: 0)
        }

        for appFolder in appFolders where !appFolder.hasPrefix(".") {
            if browserRootNames.contains(appFolder) { continue }
            let appBasePath = (appSupportRoot as NSString).appendingPathComponent(appFolder)
            var isDir: ObjCBool = false
            guard fm.fileExists(atPath: appBasePath, isDirectory: &isDir), isDir.boolValue else { continue }

            // Check if the root Application Support folder is protected (e.g., MobileSync, AddressBook, TCC)
            if safetyEngine.exclusionTree.isPathOrAncestorExcluded(appBasePath) {
                skipped += 1
                continue
            }

            let resolved = appCatalog.resolve(folderOrBundleIdentifier: appFolder)
            let isAIApp =
                aiDesktopAppFolderNames.contains(appFolder)
                || resolved.displayName.localizedCaseInsensitiveContains("Claude")
                || resolved.displayName.localizedCaseInsensitiveContains("Antigravity")
                || resolved.displayName.localizedCaseInsensitiveContains("Cursor")
            let targetCategory: CleanupCategory = isAIApp ? .aiAndAgentRuntimes : .webAndElectronCaches

            for spec in rules.verifiedElectronCacheSubfolders {
                // Avoid double-scanning Cache/Cache_Data since Cache covers the entire Chromium cache directory
                if spec.subpath == "Cache/Cache_Data" { continue }

                let targetPath = (appBasePath as NSString).appendingPathComponent(spec.subpath)
                var subIsDir: ObjCBool = false
                guard fm.fileExists(atPath: targetPath, isDirectory: &subIsDir), subIsDir.boolValue else { continue }

                let verdict = safetyEngine.evaluate(
                    path: targetPath,
                    category: targetCategory,
                    bundleIdentifier: resolved.bundleID,
                    displayName: resolved.displayName,
                    defaultConfidence: .safeAutoSelect,
                    defaultReason: spec.explanation
                )
                guard verdict.isAllowed else {
                    skipped += 1
                    continue
                }

                let metrics = DiskAllocatedSizeCalculator.measure(
                    path: targetPath,
                    protectedComponentNames: rules.protectedCacheComponents
                )
                guard metrics.allocatedBytes > 0 else { continue }

                candidates.append(
                    ScanCandidateItem(
                        path: targetPath,
                        category: targetCategory,
                        bundleIdentifier: resolved.bundleID,
                        appDisplayName: resolved.displayName,
                        itemName: "\(resolved.displayName) — \(spec.label)",
                        allocatedBytes: metrics.allocatedBytes,
                        fileCount: metrics.fileCount,
                        lastModified: metrics.latestModified,
                        confidence: verdict.confidence,
                        isRunningApp: verdict.isRunningApp,
                        ruleIdentifier: "electron.\(appFolder).\(spec.subpath)",
                        safetyExplanation: verdict.reason
                    )
                )
            }
        }

        return SubscannerResult(candidates: candidates, skippedProtectedCount: skipped)
    }
}

// MARK: - 3. Developer Toolchain & Xcode Subscanner

public struct DeveloperToolchainSubscanner: CleanupSubscanner {
    public let identifier = "scanner.developer_toolchains"
    public init() {}

    public func scan(
        safetyEngine: SafetyGuardEngine,
        appCatalog: ApplicationMetadataCatalog
    ) -> SubscannerResult {
        var candidates: [ScanCandidateItem] = []
        var skipped = 0
        let fm = FileManager.default
        let home = safetyEngine.homeDirectoryPath
        let rules = safetyEngine.rules
        var coveredDotCacheSubfolders = Set<String>()

        // 3A. Curated Developer & Xcode Recipes (evaluated in parallel across CPU cores)
        for recipe in rules.developerToolchainRecipes {
            if recipe.relativePathFromHome.hasPrefix(".cache/") {
                let sub = String(recipe.relativePathFromHome.dropFirst(".cache/".count))
                coveredDotCacheSubfolders.insert(sub)
            }
        }

        let recipes = rules.developerToolchainRecipes
        let lock = NSLock()
        DispatchQueue.concurrentPerform(iterations: recipes.count) { idx in
            let recipe = recipes[idx]
            let fullPath = (home as NSString).appendingPathComponent(recipe.relativePathFromHome)
            var isDir: ObjCBool = false
            guard FileManager.default.fileExists(atPath: fullPath, isDirectory: &isDir) else { return }

            let verdict = safetyEngine.evaluate(
                path: fullPath,
                category: recipe.category,
                bundleIdentifier: recipe.bundleIdentifier,
                displayName: recipe.displayName,
                processNames: recipe.processNames,
                defaultConfidence: recipe.confidence,
                defaultReason: recipe.explanation
            )
            guard verdict.isAllowed else {
                lock.lock()
                skipped += 1
                lock.unlock()
                return
            }

            let metrics = DiskAllocatedSizeCalculator.measure(
                path: fullPath,
                protectedComponentNames: rules.protectedCacheComponents
            )
            guard metrics.allocatedBytes > 0 else { return }

            let item = ScanCandidateItem(
                path: fullPath,
                category: recipe.category,
                bundleIdentifier: recipe.bundleIdentifier,
                appDisplayName: recipe.displayName,
                itemName: recipe.displayName,
                allocatedBytes: metrics.allocatedBytes,
                fileCount: metrics.fileCount,
                lastModified: metrics.latestModified,
                confidence: verdict.confidence,
                isRunningApp: verdict.isRunningApp,
                ruleIdentifier: recipe.id,
                safetyExplanation: verdict.reason
            )
            lock.lock()
            candidates.append(item)
            lock.unlock()
        }

        // 3B. Remaining XDG ~/.cache/* subdirectories not already covered by a specific recipe
        let dotCacheRoot = (home as NSString).appendingPathComponent(".cache")
        if let entries = try? fm.contentsOfDirectory(atPath: dotCacheRoot) {
            for entry in entries where !entry.hasPrefix(".") && !coveredDotCacheSubfolders.contains(entry) {
                let fullPath = (dotCacheRoot as NSString).appendingPathComponent(entry)
                let resolved = appCatalog.resolve(folderOrBundleIdentifier: entry)
                let verdict = safetyEngine.evaluate(
                    path: fullPath,
                    category: .developerToolchains,
                    bundleIdentifier: "xdg.cache.\(entry)",
                    displayName: "XDG Cache — \(resolved.displayName)",
                    defaultConfidence: .safeAutoSelect,
                    defaultReason:
                        "Standard XDG user cache directory (~/.cache/\(entry)); stores regenerable CLI and package artifacts."
                )
                guard verdict.isAllowed else {
                    skipped += 1
                    continue
                }
                let metrics = DiskAllocatedSizeCalculator.measure(
                    path: fullPath,
                    protectedComponentNames: rules.protectedCacheComponents
                )
                guard metrics.allocatedBytes > 0 else { continue }
                candidates.append(
                    ScanCandidateItem(
                        path: fullPath,
                        category: .developerToolchains,
                        bundleIdentifier: "xdg.cache.\(entry)",
                        appDisplayName: "XDG Cache (\(entry))",
                        itemName: "~/.cache/\(entry)",
                        allocatedBytes: metrics.allocatedBytes,
                        fileCount: metrics.fileCount,
                        lastModified: metrics.latestModified,
                        confidence: verdict.confidence,
                        isRunningApp: verdict.isRunningApp,
                        ruleIdentifier: "xdg.cache.\(entry)",
                        safetyExplanation: verdict.reason
                    )
                )
            }
        }

        // 3C. Granular CoreSimulator Device Inspection (Separating Safe Internal Caches from Installed App Containers)
        let simDevicesRoot = (home as NSString).appendingPathComponent("Library/Developer/CoreSimulator/Devices")
        if let deviceUUIDs = try? fm.contentsOfDirectory(atPath: simDevicesRoot) {
            let safeSimSubpaths: [(subpath: String, label: String, reason: String)] = [
                (
                    "data/private/var/MobileAsset",
                    "OTA System & Linguistic MobileAssets",
                    "Downloaded iOS Simulator OTA system, font, and linguistic assets; automatically re-downloaded on demand."
                ),
                (
                    "data/Library/Application Support/PRBPosterExtensionDataStore",
                    "PosterBoard Lock Screen Wallpaper Cache",
                    "Pre-rendered iOS Simulator Lock Screen / PosterBoard wallpaper cache; safely regenerated by SpringBoard."
                ),
                (
                    "data/Library/Caches",
                    "System & App Library Caches",
                    "Standard iOS Simulator internal ~/Library/Caches directory; 100% regenerable."
                ),
                (
                    "data/var/folders",
                    "Temporary Darwin User Cache (var/folders)",
                    "Per-user temporary cache and shader directories inside the iOS Simulator instance."
                ),
            ]

            for uuid in deviceUUIDs where !uuid.hasPrefix(".") {
                let deviceDir = (simDevicesRoot as NSString).appendingPathComponent(uuid)
                let plistPath = (deviceDir as NSString).appendingPathComponent("device.plist")
                guard fm.fileExists(atPath: plistPath) else { continue }

                var simName = uuid
                var simRuntime = "iOS Simulator"
                if let plistData = try? Data(contentsOf: URL(fileURLWithPath: plistPath)),
                    let plist = try? PropertyListSerialization.propertyList(from: plistData, options: [], format: nil)
                        as? [String: Any]
                {
                    if let name = plist["name"] as? String {
                        simName = name
                    }
                    if let runtimeRaw = plist["runtime"] as? String,
                        let shortRuntime = runtimeRaw.components(separatedBy: ".").last
                    {
                        simRuntime = shortRuntime.replacingOccurrences(of: "-", with: " ")
                    }
                }

                let deviceTitle = "Simulator: \(simName) (\(simRuntime))"
                let safeGroupBundleID =
                    "com.apple.CoreSimulator.SafeCache.\(simName.replacingOccurrences(of: " ", with: "_"))"

                for spec in safeSimSubpaths {
                    let targetPath = (deviceDir as NSString).appendingPathComponent(spec.subpath)
                    var isDir: ObjCBool = false
                    guard fm.fileExists(atPath: targetPath, isDirectory: &isDir), isDir.boolValue else { continue }

                    let verdict = safetyEngine.evaluate(
                        path: targetPath,
                        category: .xcodeJunk,
                        bundleIdentifier: safeGroupBundleID,
                        displayName: "\(deviceTitle) — Internal Caches",
                        processNames: ["Simulator", "launchd_sim"],
                        defaultConfidence: .safeAutoSelect,
                        defaultReason: spec.reason
                    )
                    guard verdict.isAllowed else {
                        skipped += 1
                        continue
                    }

                    let metrics = DiskAllocatedSizeCalculator.measure(
                        path: targetPath,
                        protectedComponentNames: rules.protectedCacheComponents
                    )
                    guard metrics.allocatedBytes > 0 else { continue }

                    candidates.append(
                        ScanCandidateItem(
                            path: targetPath,
                            category: .xcodeJunk,
                            bundleIdentifier: safeGroupBundleID,
                            appDisplayName: "\(deviceTitle) — Internal Caches",
                            itemName: "\(simName): \(spec.label)",
                            allocatedBytes: metrics.allocatedBytes,
                            fileCount: metrics.fileCount,
                            lastModified: metrics.latestModified,
                            confidence: verdict.confidence,
                            isRunningApp: verdict.isRunningApp,
                            ruleIdentifier: "xcode.sim.cache.\(uuid).\(spec.subpath)",
                            safetyExplanation: verdict.reason
                        )
                    )
                }

                // Installed App Containers & Sandboxes inside the Simulator (Review Recommended)
                let containersPath = (deviceDir as NSString).appendingPathComponent("data/Containers")
                var isContainerDir: ObjCBool = false
                if fm.fileExists(atPath: containersPath, isDirectory: &isContainerDir), isContainerDir.boolValue {
                    let appGroupBundleID =
                        "com.apple.CoreSimulator.AppContainers.\(simName.replacingOccurrences(of: " ", with: "_"))"
                    let verdict = safetyEngine.evaluate(
                        path: containersPath,
                        category: .xcodeJunk,
                        bundleIdentifier: appGroupBundleID,
                        displayName: "\(deviceTitle) — Installed Apps & Data",
                        processNames: ["Simulator", "launchd_sim"],
                        defaultConfidence: .reviewRecommended,
                        defaultReason:
                            "Installed test app binaries (e.g. Runner.app) and app sandbox databases inside \(simName). Unchecked by default to preserve test sessions."
                    )
                    guard verdict.isAllowed else {
                        skipped += 1
                        continue
                    }
                    let metrics = DiskAllocatedSizeCalculator.measure(
                        path: containersPath,
                        protectedComponentNames: rules.protectedCacheComponents
                    )
                    if metrics.allocatedBytes > 5 * 1024 * 1024 {
                        candidates.append(
                            ScanCandidateItem(
                                path: containersPath,
                                category: .xcodeJunk,
                                bundleIdentifier: appGroupBundleID,
                                appDisplayName: "\(deviceTitle) — Installed Apps & Data",
                                itemName: "\(simName): Installed App Bundles & Sandboxes (data/Containers)",
                                allocatedBytes: metrics.allocatedBytes,
                                fileCount: metrics.fileCount,
                                lastModified: metrics.latestModified,
                                confidence: verdict.confidence,
                                isRunningApp: verdict.isRunningApp,
                                ruleIdentifier: "xcode.sim.containers.\(uuid)",
                                safetyExplanation: verdict.reason
                            )
                        )
                    }
                }
            }
        }

        return SubscannerResult(candidates: candidates, skippedProtectedCount: skipped)
    }
}

// MARK: - 4. Logs & Diagnostic Reports Subscanner

public struct LogsAndDiagnosticsSubscanner: CleanupSubscanner {
    public let identifier = "scanner.logs_and_diagnostics"
    public init() {}

    public func scan(
        safetyEngine: SafetyGuardEngine,
        appCatalog: ApplicationMetadataCatalog
    ) -> SubscannerResult {
        var candidates: [ScanCandidateItem] = []
        var skipped = 0
        let fm = FileManager.default
        let home = safetyEngine.homeDirectoryPath
        let rules = safetyEngine.rules
        let recentActiveCutoff = Date().addingTimeInterval(-300)  // Skip tiny logs (<32 KB) actively written in the last 5 minutes

        // Strictly scan user-owned log & crash directories (never root-owned /private/var/log or /Library/Logs)
        let logDirectories: [(path: String, prefixID: String, label: String)] = [
            ((home as NSString).appendingPathComponent("Library/Logs"), "logs.user", "User Application Logs"),
            (
                (home as NSString).appendingPathComponent("Library/Logs/DiagnosticReports"), "logs.diag.reports",
                "User Crash & Diagnostic Reports"
            ),
            (
                (home as NSString).appendingPathComponent("Library/DiagnosticReports"), "logs.diag.user",
                "User Crash & Diagnostic Reports"
            ),
            (
                (home as NSString).appendingPathComponent("Library/Application Support/CrashReporter"),
                "logs.crashreporter", "Application Crash Reporter Logs"
            ),
        ]

        for spec in logDirectories {
            guard let entries = try? fm.contentsOfDirectory(atPath: spec.path) else { continue }
            for entry in entries where !entry.hasPrefix(".") {
                // DiagnosticReports inside ~/Library/Logs is scanned via its own dedicated spec so its root folder is preserved
                if spec.prefixID == "logs.user" && (entry == "DiagnosticReports" || entry == "Retired") {
                    continue
                }
                if entry == "Retired" {
                    continue
                }
                let fullPath = (spec.path as NSString).appendingPathComponent(entry)
                let resolved = appCatalog.resolve(folderOrBundleIdentifier: entry)
                let verdict = safetyEngine.evaluate(
                    path: fullPath,
                    category: .logsAndDiagnostics,
                    bundleIdentifier: resolved.bundleID,
                    displayName: resolved.displayName,
                    defaultConfidence: .safeAutoSelect,
                    defaultReason: "\(spec.label) (\(entry)); user-owned historical log/diagnostic data safe to purge."
                )
                guard verdict.isAllowed else {
                    skipped += 1
                    continue
                }
                let metrics = DiskAllocatedSizeCalculator.measure(
                    path: fullPath,
                    protectedComponentNames: rules.protectedCacheComponents
                )
                guard metrics.allocatedBytes > 0 else { continue }
                if metrics.allocatedBytes < 32_768,
                    let mod = metrics.latestModified,
                    mod > recentActiveCutoff
                {
                    continue
                }
                candidates.append(
                    ScanCandidateItem(
                        path: fullPath,
                        category: .logsAndDiagnostics,
                        bundleIdentifier: "\(spec.prefixID).\(resolved.bundleID)",
                        appDisplayName: resolved.displayName,
                        itemName: "\(spec.label): \(entry)",
                        allocatedBytes: metrics.allocatedBytes,
                        fileCount: metrics.fileCount,
                        lastModified: metrics.latestModified,
                        confidence: verdict.confidence,
                        isRunningApp: verdict.isRunningApp,
                        ruleIdentifier: "\(spec.prefixID).\(entry)",
                        safetyExplanation: verdict.reason
                    )
                )
            }
        }

        // Sandbox Container Logs: ~/Library/Containers/*/Data/Library/Logs/*
        let containersRoot = (home as NSString).appendingPathComponent("Library/Containers")
        if let containers = try? fm.contentsOfDirectory(atPath: containersRoot) {
            for containerID in containers where !containerID.hasPrefix(".") {
                if containerID.hasPrefix("com.apple.") { continue }
                let logDir = (containersRoot as NSString).appendingPathComponent("\(containerID)/Data/Library/Logs")
                var isDir: ObjCBool = false
                guard fm.fileExists(atPath: logDir, isDirectory: &isDir), isDir.boolValue else { continue }
                guard let logEntries = try? fm.contentsOfDirectory(atPath: logDir), !logEntries.isEmpty else {
                    continue
                }

                let resolved = appCatalog.resolve(folderOrBundleIdentifier: containerID)
                for entry in logEntries where !entry.hasPrefix(".") {
                    let entryPath = (logDir as NSString).appendingPathComponent(entry)
                    let verdict = safetyEngine.evaluate(
                        path: entryPath,
                        category: .logsAndDiagnostics,
                        bundleIdentifier: resolved.bundleID,
                        displayName: resolved.displayName,
                        defaultConfidence: .safeAutoSelect,
                        defaultReason: "Sandboxed container log files for \(resolved.displayName)."
                    )
                    guard verdict.isAllowed else {
                        skipped += 1
                        continue
                    }
                    let metrics = DiskAllocatedSizeCalculator.measure(
                        path: entryPath,
                        protectedComponentNames: rules.protectedCacheComponents
                    )
                    guard metrics.allocatedBytes > 0 else { continue }
                    if metrics.allocatedBytes < 32_768,
                        let mod = metrics.latestModified,
                        mod > recentActiveCutoff
                    {
                        continue
                    }
                    candidates.append(
                        ScanCandidateItem(
                            path: entryPath,
                            category: .logsAndDiagnostics,
                            bundleIdentifier: resolved.bundleID,
                            appDisplayName: resolved.displayName,
                            itemName: "\(resolved.displayName) Container Logs (\(entry))",
                            allocatedBytes: metrics.allocatedBytes,
                            fileCount: metrics.fileCount,
                            lastModified: metrics.latestModified,
                            confidence: verdict.confidence,
                            isRunningApp: verdict.isRunningApp,
                            ruleIdentifier: "logs.sandbox.\(containerID).\(entry)",
                            safetyExplanation: verdict.reason
                        )
                    )
                }
            }
        }

        return SubscannerResult(candidates: candidates, skippedProtectedCount: skipped)
    }
}

// MARK: - 5. Non-Destructive Browser Caches Subscanner

public struct BrowserCacheSubscanner: CleanupSubscanner {
    public let identifier = "scanner.browser_caches"
    public init() {}

    public func scan(
        safetyEngine: SafetyGuardEngine,
        appCatalog: ApplicationMetadataCatalog
    ) -> SubscannerResult {
        var candidates: [ScanCandidateItem] = []
        var skipped = 0
        let fm = FileManager.default
        let home = safetyEngine.homeDirectoryPath
        let rules = safetyEngine.rules

        for recipe in rules.browserCacheRecipes {
            // Direct cache directories in ~/Library/Caches or ~/Library/Containers
            for relPath in recipe.relativeCachePathsFromHome {
                let fullPath = (home as NSString).appendingPathComponent(relPath)
                var isDir: ObjCBool = false
                guard fm.fileExists(atPath: fullPath, isDirectory: &isDir), isDir.boolValue else { continue }

                let verdict = safetyEngine.evaluate(
                    path: fullPath,
                    category: .browserCaches,
                    bundleIdentifier: recipe.bundleIdentifier,
                    displayName: recipe.browserName,
                    defaultConfidence: .safeAutoSelect,
                    defaultReason: recipe.explanation
                )
                guard verdict.isAllowed else {
                    skipped += 1
                    continue
                }
                let metrics = DiskAllocatedSizeCalculator.measure(
                    path: fullPath,
                    protectedComponentNames: rules.protectedCacheComponents
                )
                guard metrics.allocatedBytes > 0 else { continue }
                candidates.append(
                    ScanCandidateItem(
                        path: fullPath,
                        category: .browserCaches,
                        bundleIdentifier: recipe.bundleIdentifier,
                        appDisplayName: recipe.browserName,
                        itemName: "\(recipe.browserName) Network & Media Cache",
                        allocatedBytes: metrics.allocatedBytes,
                        fileCount: metrics.fileCount,
                        lastModified: metrics.latestModified,
                        confidence: verdict.confidence,
                        isRunningApp: verdict.isRunningApp,
                        ruleIdentifier: "\(recipe.id).cache",
                        safetyExplanation: verdict.reason
                    )
                )
            }

            // Profile-level cache subpaths (Default, Profile 1, etc.)
            if let profileBaseRel = recipe.profileGlobBaseFromHome {
                let profileBase = (home as NSString).appendingPathComponent(profileBaseRel)
                if let entries = try? fm.contentsOfDirectory(atPath: profileBase) {
                    for entry in entries
                    where entry == "Default" || entry.hasPrefix("Profile ") || entry == "Guest Profile" {
                        let profilePath = (profileBase as NSString).appendingPathComponent(entry)
                        for cacheSubpath in recipe.profileCacheSubpaths {
                            let targetPath = (profilePath as NSString).appendingPathComponent(cacheSubpath)
                            var isDir: ObjCBool = false
                            guard fm.fileExists(atPath: targetPath, isDirectory: &isDir), isDir.boolValue else {
                                continue
                            }

                            let verdict = safetyEngine.evaluate(
                                path: targetPath,
                                category: .browserCaches,
                                bundleIdentifier: recipe.bundleIdentifier,
                                displayName: recipe.browserName,
                                defaultConfidence: .safeAutoSelect,
                                defaultReason: recipe.explanation
                            )
                            guard verdict.isAllowed else {
                                skipped += 1
                                continue
                            }
                            let metrics = DiskAllocatedSizeCalculator.measure(
                                path: targetPath,
                                protectedComponentNames: rules.protectedCacheComponents
                            )
                            guard metrics.allocatedBytes > 0 else { continue }
                            candidates.append(
                                ScanCandidateItem(
                                    path: targetPath,
                                    category: .browserCaches,
                                    bundleIdentifier: recipe.bundleIdentifier,
                                    appDisplayName: recipe.browserName,
                                    itemName: "\(recipe.browserName) (\(entry)) — \(cacheSubpath)",
                                    allocatedBytes: metrics.allocatedBytes,
                                    fileCount: metrics.fileCount,
                                    lastModified: metrics.latestModified,
                                    confidence: verdict.confidence,
                                    isRunningApp: verdict.isRunningApp,
                                    ruleIdentifier: "\(recipe.id).\(entry).\(cacheSubpath)",
                                    safetyExplanation: verdict.reason
                                )
                            )
                        }
                    }
                }
            }
        }

        return SubscannerResult(candidates: candidates, skippedProtectedCount: skipped)
    }
}

// MARK: - 6. Broken Preferences & Saved Application States Subscanner

public struct PreferenceAndStateHygieneSubscanner: CleanupSubscanner {
    public let identifier = "scanner.prefs_and_state"
    public init() {}

    public func scan(
        safetyEngine: SafetyGuardEngine,
        appCatalog: ApplicationMetadataCatalog
    ) -> SubscannerResult {
        var candidates: [ScanCandidateItem] = []
        var skipped = 0
        let fm = FileManager.default
        let home = safetyEngine.homeDirectoryPath
        let rules = safetyEngine.rules

        // 6A. Validate ~/Library/Preferences/*.plist for corrupted property lists
        let prefsRoot = (home as NSString).appendingPathComponent("Library/Preferences")
        if let files = try? fm.contentsOfDirectory(atPath: prefsRoot) {
            for file in files where file.hasSuffix(".plist") && !file.hasPrefix(".") {
                if file.hasPrefix("com.apple.") || file == "loginwindow.plist" || file == "pbs.plist" {
                    continue
                }
                let fullPath = (prefsRoot as NSString).appendingPathComponent(file)
                var isDir: ObjCBool = false
                guard fm.fileExists(atPath: fullPath, isDirectory: &isDir), !isDir.boolValue else { continue }

                let bundleToken = (file as NSString).deletingPathExtension
                let resolved = appCatalog.resolve(folderOrBundleIdentifier: bundleToken)
                let verdict = safetyEngine.evaluate(
                    path: fullPath,
                    category: .preferenceAndStateHygiene,
                    bundleIdentifier: resolved.bundleID,
                    displayName: resolved.displayName,
                    defaultConfidence: .safeAutoSelect,
                    defaultReason: "Malformed or truncated .plist file that fails PropertyListSerialization validation."
                )
                guard verdict.isAllowed else {
                    skipped += 1
                    continue
                }

                if Self.isCorruptedPropertyList(atPath: fullPath) {
                    let metrics = DiskAllocatedSizeCalculator.measure(path: fullPath)
                    let bytes = max(metrics.allocatedBytes, 512)
                    candidates.append(
                        ScanCandidateItem(
                            path: fullPath,
                            category: .preferenceAndStateHygiene,
                            bundleIdentifier: resolved.bundleID,
                            appDisplayName: resolved.displayName,
                            itemName: "Corrupted Preference File (\(file))",
                            allocatedBytes: bytes,
                            fileCount: 1,
                            lastModified: metrics.latestModified,
                            confidence: verdict.confidence,
                            isRunningApp: verdict.isRunningApp,
                            ruleIdentifier: "prefs.broken.\(bundleToken)",
                            safetyExplanation: verdict.reason
                        )
                    )
                }
            }
        }

        // 6B. ~/Library/Saved Application State/*.savedState
        let savedStateRoot = (home as NSString).appendingPathComponent("Library/Saved Application State")
        if let entries = try? fm.contentsOfDirectory(atPath: savedStateRoot) {
            for entry in entries where entry.hasSuffix(".savedState") {
                let fullPath = (savedStateRoot as NSString).appendingPathComponent(entry)
                let bundleToken = (entry as NSString).deletingPathExtension
                let resolved = appCatalog.resolve(folderOrBundleIdentifier: bundleToken)

                let verdict = safetyEngine.evaluate(
                    path: fullPath,
                    category: .preferenceAndStateHygiene,
                    bundleIdentifier: resolved.bundleID,
                    displayName: resolved.displayName,
                    defaultConfidence: .safeAutoSelect,
                    defaultReason:
                        "Window restoration snapshot in ~/Library/Saved Application State; safely recreated when the application runs."
                )
                guard verdict.isAllowed else {
                    skipped += 1
                    continue
                }
                // Skip currently running apps' window restoration states
                if verdict.isRunningApp {
                    skipped += 1
                    continue
                }
                let metrics = DiskAllocatedSizeCalculator.measure(
                    path: fullPath,
                    protectedComponentNames: rules.protectedCacheComponents
                )
                guard metrics.allocatedBytes > 0 else { continue }
                candidates.append(
                    ScanCandidateItem(
                        path: fullPath,
                        category: .preferenceAndStateHygiene,
                        bundleIdentifier: resolved.bundleID,
                        appDisplayName: resolved.displayName,
                        itemName: "\(resolved.displayName) Window Saved State",
                        allocatedBytes: metrics.allocatedBytes,
                        fileCount: metrics.fileCount,
                        lastModified: metrics.latestModified,
                        confidence: .safeAutoSelect,
                        isRunningApp: false,
                        ruleIdentifier: "savedstate.\(bundleToken)",
                        safetyExplanation: verdict.reason
                    )
                )
            }
        }

        return SubscannerResult(candidates: candidates, skippedProtectedCount: skipped)
    }

    /// Returns `true` if the file at `path` is either 0 bytes or fails `PropertyListSerialization` parsing.
    public static func isCorruptedPropertyList(atPath path: String) -> Bool {
        guard let data = try? Data(contentsOf: URL(fileURLWithPath: path), options: [.mappedIfSafe]) else {
            return false
        }
        if data.isEmpty {
            return true
        }
        do {
            _ = try PropertyListSerialization.propertyList(from: data, options: [], format: nil)
            return false
        } catch {
            return true
        }
    }
}

// MARK: - 7. Aged Disk Images & Installers Subscanner (>30 Days in ~/Downloads)

public struct InstallerPackageSubscanner: CleanupSubscanner {
    public let identifier = "scanner.aged_installers"
    public let minimumAgeDays: Int

    public init(minimumAgeDays: Int = 30) {
        self.minimumAgeDays = minimumAgeDays
    }

    public func scan(
        safetyEngine: SafetyGuardEngine,
        appCatalog: ApplicationMetadataCatalog
    ) -> SubscannerResult {
        var candidates: [ScanCandidateItem] = []
        var skipped = 0
        let fm = FileManager.default
        let downloadsRoot = (safetyEngine.homeDirectoryPath as NSString).appendingPathComponent("Downloads")
        let cutoffDate = Date().addingTimeInterval(-Double(minimumAgeDays) * 86400.0)

        guard let entries = try? fm.contentsOfDirectory(atPath: downloadsRoot) else {
            return SubscannerResult(candidates: [], skippedProtectedCount: 0)
        }

        for entry in entries where !entry.hasPrefix(".") {
            let ext = (entry as NSString).pathExtension.lowercased()
            guard ext == "dmg" || ext == "pkg" else { continue }

            let fullPath = (downloadsRoot as NSString).appendingPathComponent(entry)
            let verdict = safetyEngine.evaluate(
                path: fullPath,
                category: .installerPackages,
                bundleIdentifier: "macos.installer.\(ext)",
                displayName: "Disk Images & Package Installers",
                defaultConfidence: .reviewRecommended,
                defaultReason:
                    "Installer archive (.\(ext)) in ~/Downloads older than \(minimumAgeDays) days. Marked 'Review Recommended' (unselected by default) so downloads are never deleted without confirmation."
            )
            guard verdict.isAllowed else {
                skipped += 1
                continue
            }

            let metrics = DiskAllocatedSizeCalculator.measure(path: fullPath)
            guard metrics.allocatedBytes > 0 else { continue }

            if let modDate = metrics.latestModified, modDate > cutoffDate {
                // Recent installer (<30 days old) — keep untouched
                skipped += 1
                continue
            }

            candidates.append(
                ScanCandidateItem(
                    path: fullPath,
                    category: .installerPackages,
                    bundleIdentifier: "macos.installer.\(ext)",
                    appDisplayName: ext == "dmg" ? "Disk Image Installers (.dmg)" : "Package Installers (.pkg)",
                    itemName: entry,
                    allocatedBytes: metrics.allocatedBytes,
                    fileCount: metrics.fileCount,
                    lastModified: metrics.latestModified,
                    confidence: .reviewRecommended,
                    isRunningApp: false,
                    ruleIdentifier: "installer.\(entry)",
                    safetyExplanation: verdict.reason
                )
            )
        }

        return SubscannerResult(candidates: candidates, skippedProtectedCount: skipped)
    }
}
